def mkp(kind, parts):
    """kind: point/sub/f1/head; parts: строка или список (текст, fmt) с fmt = None | 'yellow' | 'red'."""
    ppr, rpr0 = TPL[kind]; p = etree.Element(q('p')); p.append(copy.deepcopy(ppr))
    for text, fmt in ([(parts, None)] if isinstance(parts, str) else parts):
        r = etree.SubElement(p, q('r')); rpr = copy.deepcopy(rpr0); fmt_rpr(rpr, fmt); r.append(rpr)
        t = etree.SubElement(r, q('t')); t.text = text; t.set(XS, 'preserve')
    return p
def after(anchor, items):
    ref = anchor
    for kind, parts in items:
        np_ = mkp(kind, parts); ref.addnext(np_); ref = np_
    return ref
def red(kind, text): return (kind, [(text, 'red')])
def siz(text): return ('sub', [(text, 'yellow')])      # СИЗ из паспорта — жёлтым, с пометкой «(из паспорта)»

# ---------- 🧩 операции с маркерами ----------
def put_parts(p, a, b, parts):
    """Заменяет символы [a,b) абзаца на несколько runs: [(текст, fmt), …]. Первый run берёт оформление исходного."""
    d.replace_in(p, a, b, parts[0][0]); pos = 0; first = None
    for r in d.truns(p):
        L = len(r.find(q('t')).text or '')
        if pos == a and r.find(q('t')).text == parts[0][0]: first = r; break
        pos += L
    fmt_rpr(run_rpr(first), parts[0][1]); ref = first
    for text, fmt in parts[1:]:
        nr = copy.deepcopy(first); nr.find(q('t')).text = text
        rpr = nr.find(q('rPr')); rpr_set(rpr, 'highlight', off=True); fmt_rpr(rpr, fmt)
        ref.addnext(nr); ref = nr
def sub_marker(pattern, parts):
    """Подстановка в каждое вхождение маркера (регулярка); parts — строка или список (текст, fmt)."""
    parts = [(parts, None)] if isinstance(parts, str) else parts
    n = 0
    while True:
        s, ps, offs = d.text(); m = re.search(pattern, s)
        if not m: break
        i, a = d.locate(m.start(), ps, offs); j, b = d.locate(m.end(), ps, offs); assert i == j, pattern
        put_parts(ps[i], a, b, parts); n += 1
    assert n, 'маркер не найден: ' + pattern
    return n
def variant(frag_start, keep):
    s, ps, offs = d.text(); m = re.search(r'\[\[ВАРИАНТ: ' + re.escape(frag_start) + r'[^\]]*\]\]', s); assert m, frag_start
    i, a = d.locate(m.start(), ps, offs); _, b = d.locate(m.end(), ps, offs); d.replace_in(ps[i], a, b, keep)
def marker_re(name): return r'\[\[ПОЛЕ: ' + re.escape(name) + r'[^\]]*\]\]'
def fill_field(name, items):
    """Вставляет items ПОСЛЕ последнего абзаца маркера [[ПОЛЕ: name …]] (чтобы не попасть под удаление), затем удаляет маркер."""
    s, ps, offs = d.text(); m = re.search(marker_re(name), s); assert m, name
    j, _ = d.locate(m.end() - 1, ps, offs)
    if items: after(ps[j], items)
    s, ps, offs = d.text(); m = re.search(marker_re(name), s); d.del_range(m.start(), m.end())

