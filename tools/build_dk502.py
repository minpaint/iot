ORDER = ['rStyle','rFonts','b','bCs','i','iCs','caps','smallCaps','strike','dstrike','outline','shadow','emboss','imprint',
         'noProof','snapToGrid','vanish','webHidden','color','spacing','w','kern','position','sz','szCs','highlight','u']
def rpr_set(rpr, tag, **attrs):
    for e in rpr.findall(q(tag)): rpr.remove(e)
    if attrs.pop('off', False): return
    el = etree.Element(q(tag))
    for k, v in attrs.items(): el.set(q(k), v)
    idx = ORDER.index(tag)
    for pos, ch in enumerate(rpr):
        name = etree.QName(ch).localname
        if name in ORDER and ORDER.index(name) > idx: rpr.insert(pos, el); return
    rpr.append(el)
def fmt_rpr(rpr, fmt):
    if fmt == 'yellow': rpr_set(rpr, 'highlight', val='yellow')
    elif fmt == 'red': rpr_set(rpr, 'strike'); rpr_set(rpr, 'color', val='FF0000')
def run_rpr(r):
    rpr = r.find(q('rPr'))
    if rpr is None: rpr = etree.Element(q('rPr')); r.insert(0, rpr)
    return rpr

