# ---------- [[ВАРИАНТ]]: решения по смыслу (листогиб, металлообработка) ----------
def variant(frag_start, keep):
    """keep: None — удалить вместе с маркером; строка — оставить этот текст."""
    s,ps,offs=d.text(); m=re.search(r'\[\[ВАРИАНТ: '+re.escape(frag_start)+r'[^\]]*\]\]',s); assert m, frag_start
    i,a=d.locate(m.start(),ps,offs); _,b=d.locate(m.end(),ps,offs)
    if keep is None:
        p=ps[i]; txt=d.ptext(p)
        if a>0 and txt[a-1]==' ' and b<len(txt) and txt[b]==' ': b+=1   # убрать двойной пробел
        d.del_chars(p,a,b)
    else: d.replace_in(ps[i],a,b,keep)
