def mkp(kind, text):
    ppr,rpr=TPL[kind]; p=etree.Element(q('p')); p.append(copy.deepcopy(ppr))
    r=etree.SubElement(p,q('r')); r.append(copy.deepcopy(rpr))
    t=etree.SubElement(r,q('t')); t.text=text; t.set(XS,'preserve'); return p
def after(anchor_p, items):
    ref=anchor_p
    for kind,text in items:
        np_=mkp(kind,text); ref.addnext(np_); ref=np_
    return ref

