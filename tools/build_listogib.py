def sub_marker(pattern, value):
    while True:
        s,ps,offs=d.text(); m=re.search(pattern,s)
        if not m: break
        i,a=d.locate(m.start(),ps,offs); j,b=d.locate(m.end(),ps,offs); assert i==j
        d.replace_in(ps[i],a,b,value)
