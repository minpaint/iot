# 🛠 Правка боевого макета: разведение маркеров на три типа (ПОЯСНЕНИЕ / ПОЛЕ / СПРАВКА),
#    условие вокруг СИЗ «по профессии», условие про гражданско-правовой договор, поле для главы 5.
# Использование: python3 boy_edit3.py <путь к распакованному word/document.xml>
# ⚠️ Правится только текст маркеров; оформление и остальное содержимое макета не затрагиваются.
import sys, re, copy
sys.path.insert(0, '/home/claude/tools')
from iotlib import Doc, q, XS

d = Doc(sys.argv[1])
log = []

def one_para(s, ps, offs, a, b):
    """Возвращает (абзац, смещение a, смещение b) для диапазона, лежащего в одном абзаце."""
    i, la = d.locate(a, ps, offs)
    j, lb = d.locate(b - 1, ps, offs)
    assert i == j, 'Токен маркера разорван между абзацами: %r' % s[a:b]
    return ps[i], la, la + (b - a)

def retype(prefix, new_open, nth=0):
    """🔁 Меняет «[[ПОЯСНЕНИЕ:» на new_open у маркера, текст которого начинается с prefix.
    Исходный текст остаётся как подсказка внутри маркера."""
    s, ps, offs = d.text()
    ms = [m for m in re.finditer(r'\[\[ПОЯСНЕНИЕ:(?=\s*' + re.escape(prefix) + ')', s)]
    assert len(ms) > nth, ('не найден маркер', prefix, len(ms))
    m = ms[nth]
    p, a, b = one_para(s, ps, offs, m.start(), m.end())
    d.replace_in(p, a, b, new_open)
    log.append('retype: %s -> %s' % (prefix[:30], new_open))

def set_ptext(p, txt):
    """Кладёт весь текст в первый run абзаца, остальные текстовые runs удаляет."""
    rs = d.truns(p)
    t = rs[0].find(q('t')); t.text = txt; t.set(XS, 'preserve')
    for r in rs[1:]:
        r.getparent().remove(r)

# ---------- 1. Гражданско-правовой договор: пометку разработчику удаляем, абзац — под отдельное условие ----------
s, ps, offs = d.text()
m = re.search(r'\[\[ПОЯСНЕНИЕ: \(этот абзац оставляем', s)
end = s.index(']]', m.start()) + 2
d.del_range(m.start(), end)
s, ps, offs = d.text()
m = re.search(r'\[\[ЕСЛИ: (инструкция по виду работ)\]\] Работающий по гражданско-правовому договору', s)
p, a, b = one_para(s, ps, offs, m.start(1), m.end(1))
d.replace_in(p, a, b, 'работа по гражданско-правовому договору')
log.append('ГПД: пометка удалена, условие переименовано')

# ---------- 2. Глава 5: добавляем необязательное поле (клон абзаца «дополнительные требования» гл.4) ----------
src = d.para_with('[[ПОЯСНЕНИЕ: В эту главу также можно добавить', n=3)[2]
new_p = copy.deepcopy(src)
set_ptext(new_p, '[[ПОЛЕ: дополнительные требования главы 5 | необяз | В эту главу также можно добавить '
                 'дополнительные, характерные для конкретной организации требования по охране труда '
                 'в аварийных ситуациях.]]')
tel = d.para_with('Телефоны аварийных служб:', n=1)[0]
tel.addprevious(new_p)
log.append('гл.5: добавлено поле дополнительных требований')

# ---------- 3. Разведение типов маркеров ----------
retype('при наличии ограничений по полу', '[[ПОЛЕ: ограничения по полу | необяз |')
retype('(указать:', '[[ПОЛЕ: вредные и опасные факторы | обяз |')
retype('Подобрать СИЗ по типовым нормам', '[[ПОЛЕ: СИЗ по типовым нормам (таблица ниже) | обяз |')
retype('(указывается от какого фактора', '[[ПОЛЕ: СИЗ для защиты (по виду работ) | обяз |')
# «В эту главу также можно добавить…» — гл.1, гл.2, гл.4 (в порядке следования в документе)
retype('В эту главу также можно добавить', '[[ПОЛЕ: дополнительные требования главы 1 | необяз |')
retype('В эту главу также можно добавить', '[[ПОЛЕ: дополнительные требования главы 2 | необяз |')
retype('В эту главу также можно добавить', '[[ПОЛЕ: дополнительные требования главы 4 | необяз |')
# ⚠️ новый абзац гл.5 уже типа ПОЛЕ, поэтому в этот список он не попадает
for n in ('33', '34', '35', '36'):
    retype('“%s.' % n, '[[СПРАВКА:')
retype('Отразить требования по охране труда при выполнении работы', '[[ПОЛЕ: требования при выполнении работы | обяз |')
retype('(указать требования безопасного обращения', '[[ПОЛЕ: исходные материалы | обяз |')
retype('(указать способы и приемы безопасной эксплуатации', '[[ПОЛЕ: транспорт, тара, грузоподъёмные механизмы | обяз |')
retype('(указать основные виды отклонений', '[[ПОЛЕ: отклонения от режима и их устранение | обяз |')
retype('(указать действия, направленные на предотвращение', '[[ПОЛЕ: взрывы, пожары, аварийные ситуации | обяз |')
retype('(указать порядок безопасного отключения', '[[ПОЛЕ: остановка, разборка, очистка и смазка | обяз |')

# ---------- 4. Условие вокруг блока СИЗ «по профессии» ----------
p_start = d.para_with('Работающий обеспечивается средствами индивидуальной защиты', n=1)[0]
# ⚠️ Подстрока встречается и в подсказке СИЗ по виду работ — нужна первая (блок по профессии идёт раньше)
p_end = d.para_with('органов дыхания от воздействия пыли, дыма, паров и газов – респираторы', n=1)[0]
rs = d.truns(p_start); t = rs[0].find(q('t'))
t.text = '[[ЕСЛИ: инструкция по профессии]] ' + (t.text or ''); t.set(XS, 'preserve')
rs = d.truns(p_end); t = rs[-1].find(q('t'))
t.text = (t.text or '') + ' [[КОНЕЦ]]'; t.set(XS, 'preserve')
log.append('СИЗ по профессии: обрамлено условием')

d.drop_empty_touched()
d.save()
print('\n'.join(log))
